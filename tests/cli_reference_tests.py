#!/usr/bin/env python3
"""docs/usage.md lists every npu-sim option as the simulator's --help prints it.

The option tables are generated by tools/gen_cli_reference.py; this suite fails when the
committed tables drift from the build, and checks the generator's parsing and escaping.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import subprocess
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOOL = ROOT / "tools" / "gen_cli_reference.py"
BINARY: Path


def load_generator():
    spec = importlib.util.spec_from_file_location("gen_cli_reference", TOOL)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    # dataclasses resolves the module's annotations through sys.modules.
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


gen = load_generator()


def simulator_help() -> str:
    return subprocess.run(
        [str(BINARY), "--help"], capture_output=True, text=True, timeout=30, check=True
    ).stdout


def leaf_paths(node: dict, prefix: str = ""):
    for key, value in node.items():
        path = f"{prefix}.{key}" if prefix else key
        if isinstance(value, dict):
            yield from leaf_paths(value, path)
        else:
            yield path


class CliReference(unittest.TestCase):
    def test_committed_tables_match_the_build(self):
        result = subprocess.run(
            [sys.executable, str(TOOL), "--check", "--binary", str(BINARY)],
            capture_output=True,
            text=True,
            timeout=60,
        )
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_every_flag_in_help_is_a_row(self):
        text = simulator_help()
        rows = gen.parse_help(text)
        documented = {row.flag for section in rows.values() for row in section if row.flag}
        printed = {
            line.split()[0]
            for line in text.splitlines()
            if line.startswith("  --") and not line.startswith("   ")
        }
        self.assertEqual(documented, printed)
        self.assertIn("--config", {row.flag for row in rows["run"]})
        self.assertIn("--timing-only", {row.flag for row in rows["config"]})

    def test_every_echoed_config_key_is_a_row(self):
        described = subprocess.run(
            [str(BINARY), "--describe-config"],
            capture_output=True,
            text=True,
            timeout=30,
            check=True,
        ).stdout
        keys = {row.key for row in gen.parse_help(simulator_help())["config"]}
        self.assertEqual(set(leaf_paths(json.loads(described))), keys)

    def test_row_fields(self):
        rows = gen.parse_help(simulator_help())
        by_key = {row.key: row for row in rows["config"]}
        self.assertEqual(by_key["shape.m"].flag, "--m")
        self.assertEqual(by_key["arch.memory.model"].value, "serial|axi")
        self.assertEqual(by_key["quant.relu"].value, "")
        self.assertEqual(by_key["quant.shifts"].flag, "")
        self.assertNotIn("(default", by_key["mapping.tile_k"].help)
        slice_cycles = {row.flag: row for row in rows["run"]}["--slice-cycles"]
        self.assertEqual(slice_cycles.value, "N")
        self.assertRegex(slice_cycles.default, r"^[0-9]+$")

    def test_cells_escape_markdown(self):
        self.assertEqual(gen.cell("a|b x*y <t> see --m"), "a\\|b x\\*y &lt;t> see `--m`")
        self.assertEqual(gen.code("os|ws"), "`os\\|ws`")
        self.assertEqual(gen.code(""), "")

    def test_unexpected_help_layout_is_rejected(self):
        with self.assertRaisesRegex(ValueError, "without a description"):
            gen.parse_help("Run control:\n  --config FILE\n\nConfiguration:\n")
        with self.assertRaisesRegex(ValueError, "unexpected configuration row"):
            gen.parse_help(
                "Run control:\n  --help\n      help\nConfiguration\n"
                "  --m N shape.m extra\n      rows\n"
            )
        with self.assertRaisesRegex(ValueError, "lacks"):
            gen.parse_help("no option rows here\n")

    def test_drift_is_reported_and_replacement_is_exact(self):
        tables = gen.render(gen.parse_help(simulator_help()))
        empty = "".join(f"<!-- generated:{name} -->\n<!-- end:{name} -->\n" for name in tables)
        filled = gen.replace_sections("# Title\n\n" + empty + "Tail.\n", tables)
        self.assertTrue(filled.startswith("# Title\n\n") and filled.endswith("Tail.\n"))
        self.assertEqual(gen.drift(filled, tables), [])
        stale = filled.replace("| `--m` |", "| `--rows` |", 1)
        self.assertEqual(len(gen.drift(stale, tables)), 1)
        with self.assertRaisesRegex(ValueError, "lacks the markers"):
            gen.replace_sections("# Title\n", tables)


def main() -> int:
    global BINARY
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", type=Path, required=True)
    args = parser.parse_args()
    BINARY = args.binary.resolve()
    if not BINARY.is_file():
        parser.error(f"simulator binary not found: {BINARY}")
    suite = unittest.defaultTestLoader.loadTestsFromTestCase(CliReference)
    result = unittest.TextTestRunner(verbosity=2).run(suite)
    return 0 if result.wasSuccessful() else 1


if __name__ == "__main__":
    sys.exit(main())
